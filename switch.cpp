#include<iostream>
using namespace std;
int main()
{

    char ch;
    cout<<"Enter any character:";
    cin>>ch;
    switch(ch){
       case 'A':cout<<"A alphabet";
       break;
       case 'B':cout<<"B alphabet";
       break;
       case 'C':cout<<"C alphabet";
       break;
       default:cout<<"not valid";


    }
}
